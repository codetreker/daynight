import { fireEvent, screen, waitFor } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ApiError } from '../src/api/client';
import type { ScopeCatalog } from '../src/api/credential-scope';
import type { ScopedConsentView } from '../src/api/scoped-authorization';
import { ScopedOAuthConsentPage } from '../src/features/auth/ScopedOAuthConsentPage';
import { createLocaleRender } from './helpers/renderWithLocale';

const render = createLocaleRender('en');
const id = '00000000-0000-4000-8000-000000000001';
const user = { personalTeam: { id: '00000000-0000-4000-8000-000000000701', kind: 'personal' as const, name: null }, id, name: 'Alice', email: 'alice@example.com', emailVerified: true, avatarUrl: null };
const revision = 'a'.repeat(64), nextRevision = 'b'.repeat(64);
const view: ScopedConsentView = { requestId: id, userId: id, status: 'pending', clientName: 'Example', clientId: 'client', clientProvenance: 'dcr', redirectUri: 'http://127.0.0.1:41235/callback', resource: 'https://daynight.example/mcp', scope: 'daynight:mcp', codeExpired: false, catalogRevision: revision };
const catalog: ScopeCatalog = { catalogRevision: revision, groups: [{ id: 'task', scopeIds: ['task:read', 'task:write'] }, { id: 'team', scopeIds: ['team:read', 'team:write'] }], defaultScopes: ['task:read', 'task:write', 'team:read'] };
const fixture = () => ({ inspect: vi.fn().mockResolvedValue(view), catalog: vi.fn().mockResolvedValue({ pat: catalog, mcp: catalog }), decide: vi.fn().mockImplementation(async (_view, _decision, _selection, _signal, _unauthorized, dispatch) => { dispatch?.(); return 'http://127.0.0.1:41235/callback?code=x'; }) });
const page = (transport: ReturnType<typeof fixture>) => <ScopedOAuthConsentPage requestId={id} user={user} transport={transport} onSwitchAccount={() => {}} onIdentityMismatch={() => {}} navigate={() => {}} />;
afterEach(() => { sessionStorage.clear(); vi.restoreAllMocks(); });

describe('scoped OAuth consent', () => {
  it('requires removing retired Steps selections when the pending catalog changes', async () => {
    const old: ScopeCatalog = { ...catalog, groups: [...catalog.groups, { id: 'step', scopeIds: ['step:read', 'step:write'] }], defaultScopes: [...catalog.defaultScopes, 'step:read', 'step:write'] };
    const updated: ScopeCatalog = { ...catalog, catalogRevision: nextRevision };
    const api = fixture(); api.inspect.mockResolvedValueOnce(view).mockResolvedValue({ ...view, catalogRevision: nextRevision });
    api.catalog.mockResolvedValueOnce({ pat: old, mcp: old }).mockResolvedValue({ pat: updated, mcp: updated });
    api.decide.mockRejectedValueOnce(new ApiError('server', 409, 'version_conflict'));
    render(page(api)); fireEvent.click(await screen.findByRole('button', { name: 'Allow access' }));
    await screen.findByText(/Previously selected permissions are unavailable: step:read, step:write/);
    fireEvent.click(screen.getByRole('button', { name: 'I reviewed the permissions' }));
    expect(screen.getByRole('button', { name: 'Allow access' })).toBeDisabled();
    fireEvent.click(screen.getByRole('button', { name: 'Remove unavailable permissions' }));
    expect(screen.queryByRole('checkbox', { name: /Steps/ })).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Allow access' }));
    await screen.findByRole('heading', { name: 'Authorization request approved' });
    expect(api.decide.mock.calls[1]?.[2]).toEqual({ catalogRevision: nextRevision, scopes: catalog.defaultScopes });
  });
  it('uses the catalog defaults and submits the actual selection, or denies without one', async () => {
    const api = fixture(); const rendered = render(page(api));
    const allow = await screen.findByRole('button', { name: 'Allow access' });
    expect(allow).toBeEnabled();
    expect(screen.getByText('Selected 3')).toBeInTheDocument();
    const groups = document.querySelectorAll('details.credential-scope-group');
    expect([...groups].every(group => !group.hasAttribute('open'))).toBe(true);
    fireEvent.click(screen.getByText('Tasks'));
    fireEvent.click(screen.getByRole('checkbox', { name: /Create tasks and edit basic details/ }));
    fireEvent.click(allow);
    await screen.findByRole('heading', { name: 'Authorization request approved' });
    expect(api.decide).toHaveBeenCalledOnce();
    expect(api.decide.mock.calls[0]?.[2]).toEqual({ catalogRevision: revision, scopes: ['task:read', 'team:read'] });
    rendered.unmount();
    const deny = fixture(); render(page(deny));
    fireEvent.click(await screen.findByRole('button', { name: 'Deny' }));
    await screen.findByRole('heading', { name: 'Access denied' });
    expect(deny.decide.mock.calls[0]?.[2]).toBeUndefined();
  });
  it('requires a nonempty selection and known descriptions', async () => {
    const api = fixture(); api.catalog.mockResolvedValue({ pat: catalog, mcp: { ...catalog, defaultScopes: [] } }); render(page(api));
    expect(await screen.findByRole('button', { name: 'Allow access' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Deny' })).toBeEnabled();
  });
  it('preserves the open selector, focused control and draft when a background catalog read fails', async () => {
    const api = fixture();
    api.catalog.mockResolvedValueOnce({ pat: catalog, mcp: catalog }).mockRejectedValueOnce(new ApiError('network')).mockResolvedValue({ pat: catalog, mcp: catalog });
    render(page(api)); await screen.findByRole('button', { name: 'Allow access' });
    fireEvent.click(screen.getByText('Tasks'));
    const input = screen.getByRole('checkbox', { name: /Create tasks and edit basic details/ });
    fireEvent.click(input); input.focus();
    const group = input.closest('details');
    fireEvent.focus(window);
    await screen.findByText('Unable to read the permissions catalog. Read it again.');
    expect(group).toHaveAttribute('open');
    expect(input).toHaveFocus();
    expect(input).not.toBeChecked();
    expect(screen.getByRole('button', { name: 'Allow access' })).toBeDisabled();
    fireEvent.click(input);
    expect(input).toBeChecked();
    fireEvent.click(screen.getByRole('button', { name: 'Read request again' }));
    await waitFor(() => expect(screen.getByRole('button', { name: 'Allow access' })).toBeEnabled());
    expect(group).toHaveAttribute('open');
    expect(input).toBeChecked();
  });
  it('keeps the draft on a catalog conflict, requiring explicit review before another approval', async () => {
    const updated: ScopeCatalog = { ...catalog, catalogRevision: nextRevision, defaultScopes: ['task:read'], groups: [{ id: 'task', scopeIds: ['task:read', 'task:write'] }, { id: 'team', scopeIds: ['team:read', 'team:write'] }] };
    const api = fixture(); api.inspect.mockResolvedValueOnce(view).mockResolvedValue({ ...view, catalogRevision: nextRevision });
    api.catalog.mockResolvedValueOnce({ pat: catalog, mcp: catalog }).mockResolvedValue({ pat: updated, mcp: updated });
    api.decide.mockImplementationOnce(async (_view, _decision, _selection, _signal, _unauthorized, dispatch) => { dispatch?.(); throw new ApiError('server', 409, 'version_conflict'); });
    render(page(api));
    fireEvent.click(await screen.findByText('Tasks'));
    fireEvent.click(screen.getByRole('checkbox', { name: /Create tasks and edit basic details/ }));
    fireEvent.click(screen.getByRole('button', { name: 'Allow access' }));
    await screen.findByText('The permissions catalog changed. Review your selection.');
    expect(screen.getByText('Selected 2')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Allow access' })).toBeDisabled();
    fireEvent.click(screen.getByRole('button', { name: 'I reviewed the permissions' }));
    fireEvent.click(screen.getByRole('button', { name: 'Allow access' }));
    await screen.findByRole('heading', { name: 'Authorization request approved' });
    expect(api.decide.mock.calls[1]?.[2]).toEqual({ catalogRevision: nextRevision, scopes: ['task:read', 'team:read'] });
  });
  it('does not silently remove unavailable selected permissions after a conflict', async () => {
    const updated: ScopeCatalog = { ...catalog, catalogRevision: nextRevision, groups: [{ id: 'task', scopeIds: ['task:read'] }, { id: 'team', scopeIds: ['team:read'] }] };
    const api = fixture(); api.inspect.mockResolvedValueOnce(view).mockResolvedValue({ ...view, catalogRevision: nextRevision });
    api.catalog.mockResolvedValueOnce({ pat: catalog, mcp: catalog }).mockResolvedValue({ pat: updated, mcp: updated });
    api.decide.mockRejectedValueOnce(new ApiError('server', 409, 'version_conflict'));
    render(page(api)); fireEvent.click(await screen.findByRole('button', { name: 'Allow access' }));
    await screen.findByText(/Previously selected permissions are unavailable: task:write/);
    fireEvent.click(screen.getByRole('button', { name: 'I reviewed the permissions' }));
    expect(screen.getByRole('button', { name: 'Allow access' })).toBeDisabled();
    fireEvent.click(screen.getByRole('button', { name: 'Remove unavailable permissions' }));
    expect(screen.getByRole('button', { name: 'Allow access' })).toBeEnabled();
  });
  it('passes account mismatch handling to the decision transport', async () => {
    const api = fixture(); const mismatch = vi.fn();
    api.decide.mockImplementation(async (_view, _decision, _selection, _signal, _unauthorized, dispatch, onMismatch) => { dispatch?.(); onMismatch?.(); throw new ApiError('protocol'); });
    render(<ScopedOAuthConsentPage requestId={id} user={user} transport={api} onSwitchAccount={() => {}} onIdentityMismatch={mismatch} navigate={() => {}} />);
    fireEvent.click(await screen.findByRole('button', { name: 'Allow access' }));
    await screen.findByRole('heading', { name: 'Authorization outcome unconfirmed' });
    expect(mismatch).toHaveBeenCalledOnce();
    expect(sessionStorage.getItem(`daynight.oauth.scoped-decision.${id}`)).toBe('pending');
  });
  it('only clears a legacy marker for a pending request when old writers are drained', async () => {
    const legacy = `daynight.oauth.decision.${id}`;
    sessionStorage.setItem(legacy, 'pending');
    const api = fixture(); const rendered = render(page(api));
    await screen.findByRole('heading', { name: 'Authorization outcome unconfirmed' });
    expect(sessionStorage.getItem(legacy)).toBe('pending');
    expect(screen.queryByRole('button', { name: 'Allow access' })).toBeNull();
    rendered.unmount();
    render(<ScopedOAuthConsentPage requestId={id} user={user} transport={fixture()} legacyWritersDrained onSwitchAccount={() => {}} onIdentityMismatch={() => {}} navigate={() => {}} />);
    expect(await screen.findByRole('button', { name: 'Allow access' })).toBeEnabled();
    expect(sessionStorage.getItem(legacy)).toBeNull();
  });
  it('never clears a scoped pending marker based on drained legacy writers', async () => {
    const scoped = `daynight.oauth.scoped-decision.${id}`;
    const legacy = `daynight.oauth.decision.${id}`;
    sessionStorage.setItem(scoped, 'pending'); sessionStorage.setItem(legacy, 'pending');
    const api = fixture();
    render(<ScopedOAuthConsentPage requestId={id} user={user} transport={api} legacyWritersDrained onSwitchAccount={() => {}} onIdentityMismatch={() => {}} navigate={() => {}} />);
    await screen.findByRole('heading', { name: 'Authorization outcome unconfirmed' });
    expect(sessionStorage.getItem(scoped)).toBe('pending');
    expect(sessionStorage.getItem(legacy)).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Check authorization status' }));
    await screen.findByText('The request is still pending. Check again later.');
    expect(sessionStorage.getItem(scoped)).toBe('pending');
    expect(api.decide).not.toHaveBeenCalled();
  });
  it('clears both markers when the original request is terminal', async () => {
    const scoped = `daynight.oauth.scoped-decision.${id}`;
    const legacy = `daynight.oauth.decision.${id}`;
    sessionStorage.setItem(scoped, 'pending'); sessionStorage.setItem(legacy, 'pending');
    const api = fixture(); api.inspect.mockResolvedValue({ ...view, status: 'denied', catalogRevision: undefined }); render(page(api));
    await screen.findByRole('heading', { name: 'Access denied' });
    expect(sessionStorage.getItem(scoped)).toBeNull(); expect(sessionStorage.getItem(legacy)).toBeNull();
    expect(api.decide).not.toHaveBeenCalled();
  });
  it('keeps an unknown decision unknown after reload and only reads the same request', async () => {
    const api = fixture(); api.decide.mockImplementation(async (_view, _decision, _selection, _signal, _unauthorized, dispatch) => { dispatch?.(); throw new ApiError('network'); });
    const rendered = render(page(api)); fireEvent.click(await screen.findByRole('button', { name: 'Allow access' }));
    await screen.findByRole('heading', { name: 'Authorization outcome unconfirmed' }); rendered.unmount();
    const next = fixture(); render(page(next));
    await screen.findByRole('heading', { name: 'Authorization outcome unconfirmed' });
    next.inspect.mockResolvedValue({ ...view, status: 'approved', catalogRevision: undefined });
    fireEvent.click(screen.getByRole('button', { name: 'Check authorization status' }));
    await screen.findByRole('heading', { name: 'Approved; connection unconfirmed' });
    expect(next.decide).not.toHaveBeenCalled();
    await waitFor(() => expect(next.inspect).toHaveBeenCalledTimes(2));
  });
});
