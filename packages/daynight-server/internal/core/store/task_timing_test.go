func TestTaskTimingMigrationPreservesUnknownHistoricalIntervals(t *testing.T) {
	ctx := context.Background()
	pool := emptyPool(t)
	if err := migrate(ctx, pool, schemaMigrations[:8]); err != nil {
		t.Fatal(err)
	}
	database := &Store{Pool: pool}
	project := projectBeforeSettings(t, database, 1)
	stamp := time.Date(2026, 1, 2, 3, 4, 5, 123456000, time.UTC)
	var historical []core.Task
	for index, status := range []core.TaskStatus{core.TaskStatus("proposed"), core.TaskTodo, core.TaskInProgress, core.TaskDone} {
		id := queryID(index + 10)
		mustQueryExec(t, database, `INSERT INTO tasks (id, project_id, title, description, status, version, created_at, updated_at)
			VALUES ($1, $2, 'Historical execution', 'Preserved', $3, $4, $5, $6)`, id, project.ID, status, index+17, stamp, stamp.Add(time.Hour))
		historical = append(historical, snapshotTaskBeforeTiming(t, database, project.ID, id))
	}
	if err := migrate(ctx, pool, schemaMigrations[:12]); err != nil {
		t.Fatal(err)
	}
	for _, before := range historical {
		after := snapshotHistoricalTask(t, database, project.ID, before.ID)
		if !reflect.DeepEqual(after, before) || after.StartedAt != nil || after.CompletedAt != nil {
			t.Fatalf("historical timing or metadata was invented: before %#v after %#v", before, after)
		}
	}
	var applied time.Time
	if err := pool.QueryRow(ctx, "SELECT applied_at FROM schema_migrations WHERE version=9").Scan(&applied); err != nil {
		t.Fatal(err)
	}
	if err := migrate(ctx, pool, schemaMigrations[:12]); err != nil {
		t.Fatal(err)
	}
	var repeated time.Time
	if err := pool.QueryRow(ctx, "SELECT applied_at FROM schema_migrations WHERE version=9").Scan(&repeated); err != nil || !repeated.Equal(applied) {
		t.Fatalf("timing migration changed on restart: %v, %v", repeated, err)
	}
}

func TestTaskTimingReplacesTheLatestIntervalAndPreservesEdits(t *testing.T) {
	database := isolatedStore(t)
	ctx := context.Background()
	project := queryProject(t, database, 1)
	task := queryTask(t, database, project.ID, 11, core.TaskTodo)
	write := func(status core.TaskStatus, title string) core.Task {
		t.Helper()
		var updated core.Task
		if err := database.WriteProject(ctx, project.ID, func(tx *ProjectTx) error {
			var err error
			updated, err = tx.UpdateTask(ctx, task.ID, TaskWrite{Title: title, Status: status})
			return err
		}); err != nil {
			t.Fatal(err)
		}
		return updated
	}
	started := write(core.TaskInProgress, "Started")
	if started.StartedAt == nil || started.CompletedAt != nil || !started.StartedAt.Equal(started.UpdatedAt) || started.StartedAt.Location() != time.UTC {
		t.Fatalf("start was not generated by the status statement: %#v", started)
	}
	edited := write(core.TaskInProgress, "Edited while running")
	if !reflect.DeepEqual(edited.StartedAt, started.StartedAt) || edited.CompletedAt != nil {
		t.Fatalf("same-state metadata edit reset timing: %#v", edited)
	}
	completed := write(core.TaskDone, "Completed")
	if !reflect.DeepEqual(completed.StartedAt, started.StartedAt) || completed.CompletedAt == nil || !completed.CompletedAt.Equal(completed.UpdatedAt) || completed.CompletedAt.Before(*completed.StartedAt) {
		t.Fatalf("completion did not freeze the interval: %#v", completed)
	}
	finishedEdit := write(core.TaskDone, "Edited after completion")
	if !reflect.DeepEqual(finishedEdit.StartedAt, completed.StartedAt) || !reflect.DeepEqual(finishedEdit.CompletedAt, completed.CompletedAt) {
		t.Fatalf("completed metadata edit changed interval: %#v", finishedEdit)
	}
	reset := write(core.TaskTodo, "New attempt preparation")
	if reset.StartedAt != nil || reset.CompletedAt != nil {
		t.Fatalf("leaving a completed interval retained old timing: %#v", reset)
	}
	restarted := write(core.TaskInProgress, "New attempt")
	if restarted.StartedAt == nil || !restarted.StartedAt.After(*completed.CompletedAt) || restarted.CompletedAt != nil {
		t.Fatalf("new execution reused a previous attempt: %#v", restarted)
	}
	reentered := write(core.TaskTodo, "Paused attempt")
	if reentered.StartedAt != nil || reentered.CompletedAt != nil {
		t.Fatalf("returning to todo retained execution timing: %#v", reentered)
	}
	latest := write(core.TaskInProgress, "Latest attempt")
	if latest.StartedAt == nil || !latest.StartedAt.After(*restarted.StartedAt) || latest.CompletedAt != nil {
		t.Fatalf("actual reentry accumulated rather than replaced timing: %#v", latest)
	}
	beforeRollback := snapshotTask(t, database, project.ID, task.ID)
	failure := errors.New("reject transaction after status update")
	err := database.WriteProject(ctx, project.ID, func(tx *ProjectTx) error {
		if _, err := tx.UpdateTask(ctx, task.ID, TaskWrite{Title: "Must roll back", Status: core.TaskDone}); err != nil {
			return err
		}
		return failure
	})
	if !errors.Is(err, failure) || !reflect.DeepEqual(snapshotTask(t, database, project.ID, task.ID), beforeRollback) {
		t.Fatalf("failed transaction partially committed timing: %v", err)
	}
	legacy := queryTask(t, database, project.ID, 12, core.TaskInProgress)
	if err := database.WriteProject(ctx, project.ID, func(tx *ProjectTx) error {
		var err error
		legacy, err = tx.UpdateTask(ctx, legacy.ID, TaskWrite{Title: "Legacy completion", Status: core.TaskDone})
		return err
	}); err != nil {
		t.Fatal(err)
	}
	if legacy.StartedAt != nil || legacy.CompletedAt == nil || !legacy.CompletedAt.Equal(legacy.UpdatedAt) {
		t.Fatalf("legacy completion invented a start or lost a real end: %#v", legacy)
	}
}

func TestTaskStartAndSnapshotClockFollowTheActualLockWait(t *testing.T) {
	database := isolatedStore(t)
	project := queryProject(t, database, 1)
	task := queryTask(t, database, project.ID, 11, core.TaskTodo)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	var releaseAt time.Time
	var started core.Task
	result := make(chan error, 1)
	if err := database.WriteProject(ctx, project.ID, func(holder *ProjectTx) error {
		go func() {
			result <- database.WriteProject(ctx, project.ID, func(waiter *ProjectTx) error {
				var err error
				started, err = waiter.UpdateTask(ctx, task.ID, TaskWrite{Title: task.Title, Status: core.TaskInProgress})
				return err
			})
		}()
		waitForQueryLock(t, database, "SELECT id::text FROM projects WHERE")
		return holder.tx.QueryRow(ctx, "SELECT clock_timestamp()").Scan(&releaseAt)
	}); err != nil {
		t.Fatal(err)
	}
	if err := receiveQueryResult(t, ctx, result); err != nil {
		t.Fatal(err)
	}
	if started.StartedAt == nil || started.StartedAt.Before(releaseAt) || !started.StartedAt.Equal(started.UpdatedAt) {
		t.Fatalf("claim used pre-lock transaction time: released %v, task %#v", releaseAt, started)
	}
	if err := database.ReadSnapshot(ctx, func(snapshot *Snapshot) error {
		tasks, err := snapshot.TaskGraphTasks(ctx, project.ID, task.ID, 160)
		if err != nil {
			return err
		}
		var lower, upper time.Time
		if err := snapshot.tx.QueryRow(ctx, "SELECT clock_timestamp()").Scan(&lower); err != nil {
			return err
		}
		observed, err := snapshot.ObservedAt(ctx)
		if err != nil {
			return err
		}
		if err := snapshot.tx.QueryRow(ctx, "SELECT clock_timestamp()").Scan(&upper); err != nil {
			return err
		}
		if len(tasks) != 1 || !reflect.DeepEqual(tasks[0].StartedAt, started.StartedAt) || observed.Before(lower) || observed.After(upper) || observed.Before(*started.StartedAt) || observed.Location() != time.UTC {
			t.Fatalf("snapshot clock is not a fresh DB sample: %v <= %v <= %v, %#v", lower, observed, upper, tasks)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
}
